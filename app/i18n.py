def get_locale():
    """Return the active UI language code.

    Returns:
        str: ``zh`` or ``en``. Defaults to English.
    """
    lang = session.get("lang", LANG_EN)
    if lang not in TRANSLATIONS:
        return LANG_EN
    return lang


def get_theme():
    """Return the active UI theme name.

    Returns:
        str: ``system``, ``dark``, or ``welight``. Defaults to system.
    """
    from app.defaults import THEME_CHOICES, THEME_SYSTEM

    theme = session.get("theme", THEME_SYSTEM)
    if theme not in THEME_CHOICES:
        return THEME_SYSTEM
    return theme


def t(key, **kwargs):
    """Translate a UI string for the active locale.

    Args:
        key: Message catalog key.
        **kwargs: Optional ``str.format`` arguments.

    Returns:
        str: Localized text, or the key if missing.
    """
    catalog = TRANSLATIONS.get(get_locale(), TRANSLATIONS[LANG_EN])
    text = catalog.get(key) or TRANSLATIONS[LANG_EN].get(key, key)
    if kwargs:
        return text.format(**kwargs)
    return text
